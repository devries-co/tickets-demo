// Rasterises Natural Earth land polygons (public domain, via the world-atlas
// package) into a half-degree land/ocean bitmask and writes it to
// shared/landmask.ts. Run with: node Never-Forgotten/scripts/build-landmask.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { feature } from "topojson-client";

const W = 720;
const H = 360;

const topo = JSON.parse(readFileSync(new URL("../../node_modules/world-atlas/land-50m.json", import.meta.url), "utf8"));
const land = feature(topo, topo.objects.land);
const geometries = land.type === "FeatureCollection" ? land.features.map((f) => f.geometry) : [land.geometry];
const rings = geometries.flatMap((g) => (g.type === "Polygon" ? g.coordinates : g.coordinates.flat()));

const bits = new Uint8Array((W * H) / 8);
let landCells = 0;
for (let y = 0; y < H; y++) {
	const lat = 90 - ((y + 0.5) * 180) / H;
	// Even-odd scanline fill across every ring at this latitude.
	const xs = [];
	for (const ring of rings) {
		for (let i = 0; i < ring.length - 1; i++) {
			const [x1, y1] = ring[i];
			const [x2, y2] = ring[i + 1];
			if (y1 <= lat !== y2 <= lat) xs.push(x1 + ((lat - y1) / (y2 - y1)) * (x2 - x1));
		}
	}
	xs.sort((a, b) => a - b);
	for (let i = 0; i + 1 < xs.length; i += 2) {
		const from = Math.ceil(((xs[i] + 180) / 360) * W - 0.5);
		const to = Math.floor(((xs[i + 1] + 180) / 360) * W - 0.5);
		for (let x = Math.max(0, from); x <= Math.min(W - 1, to); x++) {
			const index = y * W + x;
			bits[index >> 3] |= 1 << (index & 7);
			landCells++;
		}
	}
}

const b64 = Buffer.from(bits).toString("base64");
writeFileSync(
	new URL("../shared/landmask.ts", import.meta.url),
	`// Generated by scripts/build-landmask.mjs from Natural Earth (public domain). Do not edit.
// ${W}x${H} equirectangular land mask, one bit per half-degree cell, row 0 at the north pole.
export const LANDMASK_W = ${W};
export const LANDMASK_H = ${H};
export const LANDMASK_B64 =
	"${b64}";
`,
);
console.log(`land cells: ${landCells} of ${W * H} (${((landCells / (W * H)) * 100).toFixed(1)}%)`);
